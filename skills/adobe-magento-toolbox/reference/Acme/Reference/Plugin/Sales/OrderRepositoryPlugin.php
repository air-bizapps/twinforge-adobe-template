declare(strict_types=1);

namespace Acme\Reference\Plugin\Sales;

use Magento\Framework\DataObject;
use Magento\Sales\Api\Data\OrderExtensionFactory;
use Magento\Sales\Api\Data\OrderInterface;
use Magento\Sales\Api\Data\OrderSearchResultInterface;
use Magento\Sales\Api\OrderRepositoryInterface;

/**
 * Plugin on a CORE service contract: exposes sales_order.acme_reference_note as the extension
 * attribute declared in etc/extension_attributes.xml (REST GET /V1/orders/:id shows it under
 * extension_attributes).
 *
 * Pattern: fill the attribute in afterGet AND afterGetList (lists do not call get()); keep the
 * existing extension object, since other modules fill it too; an after plugin may omit the
 * original arguments it does not use.
 */
class OrderRepositoryPlugin
{
    /**
     * @param OrderExtensionFactory $extensionFactory generated by Magento from the interface name
     */
    public function __construct(
        private readonly OrderExtensionFactory $extensionFactory
    ) {
    }

    /**
     * @param OrderRepositoryInterface $subject
     * @param OrderInterface $result
     * @return OrderInterface
     */
    public function afterGet(OrderRepositoryInterface $subject, OrderInterface $result): OrderInterface
    {
        $this->addNote($result);
        return $result;
    }

    /**
     * @param OrderRepositoryInterface $subject
     * @param OrderSearchResultInterface $result
     * @return OrderSearchResultInterface
     */
    public function afterGetList(
        OrderRepositoryInterface $subject,
        OrderSearchResultInterface $result
    ): OrderSearchResultInterface {
        foreach ($result->getItems() as $order) {
            $this->addNote($order);
        }
        return $result;
    }

    /**
     * @param OrderInterface $order
     * @return void
     */
    private function addNote(OrderInterface $order): void
    {
        $extension = $order->getExtensionAttributes() ?? $this->extensionFactory->create();
        $note = $order instanceof DataObject ? $order->getData('acme_reference_note') : null;
        $extension->setAcmeReferenceNote($note === null ? null : (string)$note);
        $order->setExtensionAttributes($extension);
    }
}
